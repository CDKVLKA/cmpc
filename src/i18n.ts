export type StringKey = keyof typeof de;

const tables: Record<Lang, typeof de> = { de, en };

export function translateUi(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const template = tables[lang][key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function countLabel(lang: Lang, n: number): string {
  const formatted = n.toLocaleString(lang === "de" ? "de-DE" : "en-US");
  if (n === 1) return translateUi(lang, "resultsOne");
  return translateUi(lang, "resultsMany", { n: formatted });
}

export function pendingLabel(lang: Lang, n: number): string {
  if (n === 1) return translateUi(lang, "pendingOne");
  return translateUi(lang, "pendingMany", { n });
}
